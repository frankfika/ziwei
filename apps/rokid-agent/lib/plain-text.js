/**
 * 把后端返回的「带 Markdown 的长文本」压成**单色绿屏能读**的纯文本。
 *
 * ── 为什么需要它 ──────────────────────────────────────────────────
 * 眼镜是**单色绿屏**（480×352，#40FF5E 四档亮度，不支持彩色）。
 * 后端返回的解读正文与追问回答是**带 Markdown 的富文本**：
 *
 *   - 强调标记 `**【福德总览】**` —— 界面上就是一串星号，纯噪声；
 *   - 标题井号 `## ✦ 双星同宫 ·「武曲破军」` —— 井号同样只是噪声；
 *   - 装饰符号 ✦ ▸ ▍ ⚙ ⚠ 与彩色圆点 🟢🔵🔴🟡 —— 单色屏上要么是方块，要么是噪点。
 *
 * 这些标记**在网页上看是排版，在眼镜上全是垃圾**。
 * 2026-11-13 渲染提审预览视频时实测：回答正文里 46 处 `**`、9 个 emoji，
 * 视频画面上就是一坨 `🔵 **贪狼化权**（落福德·你夫妻的三合）`。
 *
 * ── 边界 ──────────────────────────────────────────────────────────
 * 这个函数**只删标记，不改内容**：
 *   - 文字一个字都不动（项目硬规则：解读正文必须来自数据集原文）；
 *   - 只去掉 Markdown 的**语法符号**和装饰性 emoji；
 *   - 段落结构（换行）保留 —— 眼镜上的 `<text>` 按 `\n` 换行。
 *
 * 引文模式标注（`citationModeLabel`）不在这里处理 ——
 * 那是**必须披露**的合规信息，不能和正文一起被洗掉。
 */

/**
 * 装饰性几何符号：单色屏上没有任何意义。
 *
 * ⚠️ 后面跟 `[ \t]*`：原文里符号与文字之间本来就有一个空格
 * （`✦ 右弼`、`【⚠️ 风险提醒】`），只删符号会留下 `【 风险提醒】` 这种多一个空格的怪东西。
 * 用 `[ \t]*` 而不是 `\s*` 是为了**不吃掉换行** ——
 * 符号在行尾时不能把段落结构也带走。
 */
const DECOR_SYMBOLS = /[\u2726\u25B8\u258D\u2699\u26A0\uFE0F\uFE0E][ \t]*/g;

/**
 * 彩色 emoji（四化标记 🔵🟢🔴🟡 等）：单色屏上会变成方块。
 */
const COLOR_EMOJI = /[\u{1F300}-\u{1FAFF}][ \t]*/gu;

/**
 * 把一段 Markdown 文本压成纯文本。
 *
 * @param {unknown} md 原始文本（通常是解读维度正文或追问回答）
 * @returns {string}
 */
export function toPlainText(md) {
  if (md === null || md === undefined) return '';
  let s = String(md);
  if (!s.trim()) return '';

  /**
   * ① 水平分隔线整行去掉。
   *
   * 原文用 `---` 分段，在绿屏上是一排短横线 —— 换成空行即可，
   * 段落感靠空行给，不靠横线。
   */
  s = s.replace(/^[ \t]*(-{3,}|\*{3,}|_{3,})[ \t]*$/gm, '');

  /**
   * ② 去掉行首的 Markdown 语法：标题井号、引用符号、列表符号。
   *
   * ⚠️ 只去**标记**，标题文字本身留着 ——
   * 「## ✦ 双星同宫 ·「武曲破军」」去掉井号后是「双星同宫 ·「武曲破军」」，
   * 这句话是有信息量的，删掉就变成丢内容。
   */
  s = s.replace(/^[ \t]*#{1,6}[ \t]+/gm, '');
  s = s.replace(/^[ \t]*>[ \t]?/gm, '');
  s = s.replace(/^[ \t]*[-+][ \t]+/gm, '');

  /**
   * ③ 去掉装饰性符号与彩色 emoji。
   *
   * ⚠️ **不删 ★（U+2605）**：原文里 `★校勘 2026-09-05：…` 是**校勘说明**，
   * 是内容的一部分（说明某条引文的出处核对情况），删掉等于丢信息。
   *
   * ⚠️ **连符号后面的空格一起吃掉**（`[ \t]*` 而不是 `\s*`）：
   * 原文里符号与文字之间本来就有一个空格（`✦ 右弼`、`【⚠️ 风险提醒】`），
   * 只删符号会留下 `【 风险提醒】` 这种多一个空格的怪东西。
   * 用 `[ \t]*` 而不是 `\s*` 是为了**不吃掉换行** ——
   * 符号在行尾时（`…左辅：\n✦`）不能把段落结构也带走。
   */
  s = s.replace(DECOR_SYMBOLS, '');
  s = s.replace(COLOR_EMOJI, '');

  /**
   * ④ 去掉强调标记。
   *
   * - `**粗体**` → 内容（原文里 46 处，是最大的噪声源）；
   * - `` `代码` `` → 内容；
   * - `*斜体*` → 内容，但**限长 60 字且不跨行** ——
   *   原文里有未闭合的 `*`（例如 `*财星配先锋，…`），
   *   不限长的话正则会一路吃到下一个 `*`，把中间整段内容吃掉。
   */
  s = s.replace(/\*\*([\s\S]*?)\*\*/g, '$1');
  s = s.replace(/`([^`]*)`/g, '$1');
  s = s.replace(/\*([^*\n]{1,60})\*/g, '$1');

  /**
   * ⑤ 收拾剩下的孤星。
   *
   * 未闭合的行首 `*`（斜体开头）与行尾 `*`（斜体结尾漏了）都是噪声。
   */
  s = s.replace(/^[ \t]*\*[ \t]*/gm, '');
  s = s.replace(/\*+$/gm, '');

  /**
   * ⑥ 收尾。
   *
   * - 行尾空白（`\n` 前的空格在绿屏上会撑出空隙）；
   * - 连续 3 个以上换行压成 2 个（原文的分隔线清掉后会留一串空行）；
   * - 整体去掉首尾空白。
   */
  s = s.replace(/[ \t]+$/gm, '');
  s = s.replace(/\n{3,}/g, '\n\n');
  return s.trim();
}

/**
 * 取出正文里的**第一句**（用于中宫摘要的兜底）。
 *
 * 为什么单独一个函数：摘要在中宫只有 220px 宽，
 * 长句会被挤爆；而解读正文第一句通常就是结论（「你是天生的守护者……」）。
 *
 * @param {unknown} text
 * @param {number} [max] 最长字数
 * @returns {string}
 */
export function firstSentence(text, max = 40) {
  const s = toPlainText(text);
  if (!s) return '';
  const m = s.match(/^[^。！？\n]{1,200}/);
  const one = (m ? m[0] : s).trim();
  if (one.length <= max) return one;
  return `${one.slice(0, Math.max(0, max - 1))}…`;
}
